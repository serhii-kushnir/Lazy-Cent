CREATE TABLE family (
                        id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        name        VARCHAR(100) NOT NULL,
                        invite_code VARCHAR(12)  NOT NULL,
                        owner_id    BIGINT       NOT NULL,
                        created_at  TIMESTAMP    NOT NULL,
                        CONSTRAINT uk_family_name        UNIQUE (name),
                        CONSTRAINT uk_family_invite_code UNIQUE (invite_code),
                        CONSTRAINT fk_family_owner FOREIGN KEY (owner_id) REFERENCES users(id)
);

ALTER TABLE users ADD COLUMN family_id BIGINT;
ALTER TABLE users ADD CONSTRAINT fk_users_family
    FOREIGN KEY (family_id) REFERENCES family(id);

-- Прискорює findByFamily(user.getFamily()) при побудові списку учасників
CREATE INDEX idx_users_family ON users (family_id);