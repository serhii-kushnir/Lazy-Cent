-- =====================================================================
-- V3 — optimistic locking для category
-- =====================================================================
-- Без цієї колонки два паралельні UPDATE-и однієї категорії (дві вкладки
-- браузера) можуть загубити зміну одного з них (lost update).
--
-- DEFAULT 0 — щоб існуючі рядки отримали валідне значення одразу.
-- Hibernate потім оновлює version при кожному UPDATE.
-- =====================================================================

ALTER TABLE category ADD COLUMN version BIGINT NOT NULL DEFAULT 0;